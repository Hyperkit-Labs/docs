const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const repoRoot = path.join(__dirname, '..');

/**
 * Paths (repo-relative, posix) that affect every documentation page UI and chrome.
 * "Last updated" reflects the newest change among the page file and these influencers.
 */
const SHARED_PAGE_INFLUENCERS = [
  'app/layout.tsx',
  'app/globals.css',
  'components/pages/docs-header.tsx',
  'components/pages/docs-sidebar.tsx',
  'components/pages/docs-toc.tsx',
  'components/pages/docs-search-modal.tsx',
  'components/pages/docs-codeblock.tsx',
  'components/pages/docs-callout.tsx',
  'components/pages/docs-mermaid.tsx',
  'components/pages/docs-status-code-table.tsx',
  'components/providers/theme-provider.tsx',
  'components/providers/smooth-scroll-provider.tsx',
  'lib/docs-nav.ts',
];

function toPosixRel(absFilePath) {
  return path.relative(repoRoot, absFilePath).split(path.sep).join('/');
}

function maxMtimeIso(absPaths) {
  let maxMs = 0;
  for (const p of absPaths) {
    try {
      const t = fs.statSync(p).mtimeMs;
      if (t > maxMs) maxMs = t;
    } catch {
      /* skip */
    }
  }
  return maxMs ? new Date(maxMs).toISOString() : new Date().toISOString();
}

/**
 * Latest commit date touching the page or any shared influencer (single git invocation).
 */
function getLastCommitDateForPage(pageAbsPath) {
  const absPaths = [pageAbsPath];
  for (const rel of SHARED_PAGE_INFLUENCERS) {
    const f = path.join(repoRoot, rel);
    if (fs.existsSync(f)) absPaths.push(f);
  }

  const pathSpecs = absPaths.map((p) => toPosixRel(p));
  const quoted = pathSpecs.map((p) => `"${p.replace(/"/g, '\\"')}"`).join(' ');

  try {
    const gitCommand = `git log -1 --format=%ci -- ${quoted}`;
    const dateString = execSync(gitCommand, { encoding: 'utf-8', cwd: repoRoot }).trim();

    if (!dateString) {
      return maxMtimeIso(absPaths);
    }
    return new Date(dateString).toISOString();
  } catch {
    return maxMtimeIso(absPaths);
  }
}

/**
 * @deprecated Use getLastCommitDateForPage; kept for callers that only pass one path.
 */
function getLastCommitDate(filePath) {
  return getLastCommitDateForPage(filePath);
}

/**
 * Generate last updated metadata for all pages
 */
function generateLastUpdatedMetadata() {
  const appDir = path.join(repoRoot, 'app');
  const metadata = {};

  function scanDirectory(dir, routePath = '') {
    const entries = fs.readdirSync(dir, { withFileTypes: true });

    for (const entry of entries) {
      const fullPath = path.join(dir, entry.name);
      const route = routePath ? `${routePath}/${entry.name}` : entry.name;

      if (entry.isDirectory()) {
        scanDirectory(fullPath, route);
      } else if (entry.name === 'page.tsx' || entry.name === 'page.ts') {
        const lastUpdated = getLastCommitDateForPage(fullPath);
        const routeKey = routePath || '/';
        metadata[routeKey] = lastUpdated;
      }
    }
  }

  scanDirectory(appDir);

  const jsonPath = path.join(repoRoot, 'lib/last-updated-metadata.json');
  fs.writeFileSync(jsonPath, JSON.stringify(metadata, null, 2));

  const tsPath = path.join(repoRoot, 'lib/last-updated-metadata.ts');
  const tsContent = `// This file is auto-generated by scripts/get-last-updated.js
// Do not edit manually - run \`npm run update-metadata\` to regenerate

export const lastUpdatedMetadata: Record<string, string> = ${JSON.stringify(metadata, null, 2)};
`;
  fs.writeFileSync(tsPath, tsContent);

  console.log('Generated last updated metadata for', Object.keys(metadata).length, 'pages');
  return metadata;
}

if (require.main === module) {
  generateLastUpdatedMetadata();
}

module.exports = { generateLastUpdatedMetadata, getLastCommitDate, getLastCommitDateForPage };
